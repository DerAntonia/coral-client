const STONE: usize = 107;

// Die Klanggruppe eines Blocks (Name ohne Namensraum); unbekannte Bloecke klingen wie Stein.
pub fn sound_group(block: &str) -> SoundGroup {
    let i = BLOCKS.binary_search_by(|(name, _)| (*name).cmp(block)).map_or(STONE, |k| BLOCKS[k].1 as usize);
    GROUPS[i].1
}

// BlockTags.INSIDE_STEP_SOUND_BLOCKS und COMBINATION_STEP_SOUND_BLOCKS (data/minecraft/tags/
// block im 1.21.11-Jar): steht so ein Block UEBER dem, auf dem man laeuft, klingt er (mit).
pub fn is_inside_step_sound(block: &str) -> bool {
    matches!(block, "powder_snow" | "sculk_vein" | "glow_lichen" | "lily_pad" | "small_amethyst_bud" | "pink_petals" | "wildflowers" | "leaf_litter")
}

pub fn is_combination_step_sound(block: &str) -> bool {
    block.ends_with("_carpet")
        || matches!(block, "snow" | "nether_sprouts" | "warped_roots" | "crimson_roots" | "resin_clump")
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn bekannte_bloecke_klingen_richtig() {
        assert_eq!(sound_group("stone").step, "block.stone.step");
        assert_eq!(sound_group("oak_planks").step, "block.wood.step");
        assert_eq!(sound_group("oak_stairs").step, "block.wood.step");
        assert_eq!(sound_group("grass_block").step, "block.grass.step");
        assert_eq!(sound_group("white_wool").step, "block.wool.step");
        assert_eq!(sound_group("gibt_es_nicht").step, "block.stone.step");
        assert!(BLOCKS.windows(2).all(|w| w[0].0 < w[1].0), "BLOCKS muss sortiert sein");
        assert!(is_combination_step_sound("red_carpet") && is_combination_step_sound("moss_carpet") && is_combination_step_sound("snow"));
        assert!(!is_combination_step_sound("stone"));
    }

    // Jeder Block der Registry hat eine Zuordnung (sonst klaenge er stillschweigend wie Stein).
    #[test]
    fn jeder_block_ist_zugeordnet() {
        let fehlend: Vec<&str> = (0..crate::block_registry::state_count() as u32)
            .filter_map(crate::block_name)
            .filter(|n| BLOCKS.binary_search_by(|(name, _)| (*name).cmp(n)).is_err())
            .collect();
        let mut fehlend = fehlend;
        fehlend.dedup();
        assert!(fehlend.is_empty(), "ohne Klanggruppe: {fehlend:?}");
    }
}

